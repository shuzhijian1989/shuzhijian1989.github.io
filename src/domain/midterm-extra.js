function fill(list, topic, stem, answer, explain, extra = {}) {
  list.push({ type: topic, topic, stem, answer: String(answer), explain,
    grade: 'fill', praise: `这道${topic}你答对了。`, ...extra })
}
function choice(list, topic, stem, values, correct, explain) {
  const options = values.map((text, i) => ({ key: String.fromCharCode(65 + i), text }))
  fill(list, topic, stem, options[correct].key, explain, { grade: 'choice', options })
}

