function numberQuestions(list, subject) {
  if (list.length !== 100) throw new Error(`${subject}新增题数应为100，实际${list.length}`)
  return list.map((item, i) => ({ subject, no: i + 21, total: 120, score: 5,
    level: ['连词成句', '图形分解', '按规律填数', '等量代换', '简单推理', '排队'].includes(item.topic) ? 'advanced' : 'basic', ...item }))
}
export const extraQuizQuestions = [...numberQuestions(chinese, '语文'), ...numberQuestions(math, '数学')]

